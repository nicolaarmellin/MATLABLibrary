%
%  MF52FORCESCOMB Compute tire forces in combined slip conditions using Pacejka MF 5.2.
%
%  Usage:
%    [Fx,Fy] = TireForces(kappa,alpha,Fz,TIR)
%    [Fx,Fy] = TireForces(kappa,alpha,Fz,TIR,"WheelIdx",wheelIdx)
%    [Fx,Fy] = TireForces(kappa,alpha,Fz,TIR,"WheelTag",wheelTag)
%    [Fx,Fy] = TireForces(kappa,alpha,Fz,TIR,"Camber",camber)
%
%  Inputs:
%    kappa     —  Slip ratio of the tire                                     [-]
%    alpha     —  Slip angle of the tire                                     [rad]
%    Fz        —  Normal load acting on the tire                             [N]
%    TIR       —  Structure with tire parameters                             [N/A]
%    wheelIdx  —  Index of the wheel (1=FL, 2=FR, 3=RL, 4=RR), default = 1   [N/A]
%    wheelTag  —  Axle-side tag of the wheel (FL, FR, RL, RR), default = ""  [N/A]
%    camber    —  Camber angle of the wheel, default = 0                     [rad]
%
%  Outputs:
%    Fx        —  Longitudinal force generated by the tire                   [N]
%    Fy        —  Lateral force generated by the tire                        [N]
%
%  Notes:
%    —  Signs of slips and forces follow the convention of the TIR coefficients:
%       if PKY1>0, Fy has the same sign as alpha (ISO-like); if PKY1<0, the
%       opposite (SAE-like).
%    —  If wheelTag is provided, an eventual wheelIdx argument is ignored.



function [Fx,Fy] = MF52ForcesComb(kappa,alpha,Fz,TIR,opts)

    arguments (Input)
        kappa          (:,1) {mustBeNumeric}
        alpha          (:,1) {mustBeNumeric}
        Fz             (:,1) {mustBeNumeric,mustBeNonnegative}
        TIR            (1,1) struct
        opts.wheelIdx  (1,1) {mustBeInteger,mustBeBetween(opts.wheelIdx,1,4)}              = 1
        opts.wheelTag  (1,1) string {mustBeMember(opts.wheelTag,["","FL","FR","RL","RR"])} = ""
        opts.camber    (1,1) {mustBeNumeric,mustBeNonpositive}                             = 0 % positive camber intentionally neglected
    end

    % resolve wheel tag if provided
    if opts.wheelTag~=""
        tagMap        = ["FL","FR","RL","RR"];
        opts.wheelIdx = find(opts.wheelTag==tagMap);
    end

    % resolve sign
    switch opts.wheelIdx
        case {1,3}, side = -1;
        case {2,4}, side = 1;
    end
    opts.camber = side*opts.camber;

    % normalize vertical load (gate nominal load at 1000 N minimum)
    if (isnan(TIR.FNOMIN))||(TIR.FNOMIN==0), TIR.FNOMIN = 1000; end
    FzNom = (Fz-TIR.FNOMIN)/TIR.FNOMIN;

    % optional TIR coefficients (0 if missing)
    TIR.PDX3 = GetParam("PDX3");
    TIR.PHY3 = GetParam("PHY3");
    TIR.PKY3 = GetParam("PKY3");
    TIR.PDY3 = GetParam("PDY3");

    % compute forces
    Fx = ComputeFx();
    Fy = ComputeFy();

    % core functions — MF 5.2
    function Fx = ComputeFx()
        Shx               = TIR.PHX1+TIR.PHX2.*FzNom;
        Svx               = Fz.*(TIR.PVX1+TIR.PVX2.*FzNom);
        Kx                = Fz.*(TIR.PKX1+TIR.PKX2.*FzNom).*exp(TIR.PKX3.*FzNom);
        Mux               = (TIR.PDX1+TIR.PDX2.*FzNom).*(1-TIR.PDX3.*opts.camber.^2);
        Dx                = Mux.*Fz;
        Cx                = TIR.PCX1;
        Bx                = Kx./max(Cx.*Dx,1e-3);
        kap_s             = kappa+Shx;
        sign_k            = sign(kap_s);
        sign_k(sign_k==0) = 1;
        Ex                = min((TIR.PEX1+TIR.PEX2.*FzNom+TIR.PEX3.*FzNom.^2).*(1-TIR.PEX4.*sign_k),1);
        Fx0               = Dx.*sin(Cx.*atan(Bx.*kap_s-Ex.*(Bx.*kap_s-atan(Bx.*kap_s))))+Svx;
        Shxa              = TIR.RHX1;
        alpha_s           = alpha+Shxa;
        Bxa               = TIR.RBX1.*cos(atan(TIR.RBX2.*kappa));
        Cxa               = TIR.RCX1;
        Exa               = min(TIR.REX1+TIR.REX2.*FzNom,1);
        num_gxa           = cos(Cxa.*atan(Bxa.*alpha_s-Exa.*(Bxa.*alpha_s-atan(Bxa.*alpha_s))));
        den_gxa           = cos(Cxa.*atan(Bxa.*Shxa-Exa.*(Bxa.*Shxa-atan(Bxa.*Shxa))));
        Gxa               = min(num_gxa./max(den_gxa,1e-6),1);
        Gxa(Gxa<0)        = 0;
        Fx                = Fx0.*Gxa;
    end
    function Fy = ComputeFy()
        Shy               = side.*(TIR.PHY1+TIR.PHY2.*FzNom)+TIR.PHY3.*opts.camber;
        Svy_base          = side.*Fz.*(TIR.PVY1+TIR.PVY2.*FzNom);
        Svy_camber        = Fz.*(TIR.PVY3+TIR.PVY4.*FzNom).*opts.camber;
        Svy               = Svy_base+Svy_camber;
        Ky                = TIR.PKY1.*TIR.FNOMIN.*sin(2.*atan(Fz./(TIR.PKY2.*TIR.FNOMIN))).*(1-TIR.PKY3.*abs(opts.camber));
        Muy               = (TIR.PDY1+TIR.PDY2.*FzNom).*(1-TIR.PDY3.*opts.camber.^2);
        Dy                = Muy.*Fz;
        Cy                = TIR.PCY1;
        By                = Ky./max(Cy.*Dy,1e-3);
        alp_s             = alpha+Shy;
        sign_a            = sign(alp_s);
        sign_a(sign_a==0) = 1;
        Ey                = min((TIR.PEY1+TIR.PEY2.*FzNom).*(1-(TIR.PEY3+TIR.PEY4.*opts.camber).*sign_a),1);
        Fy0               = Dy.*sin(Cy.*atan(By.*alp_s-Ey.*(By.*alp_s-atan(By.*alp_s))))+Svy;
        Shyk              = TIR.RHY1+TIR.RHY2.*FzNom;
        k_s               = kappa+Shyk;
        Byk               = TIR.RBY1.*cos(atan(TIR.RBY2.*(alpha-TIR.RBY3)));
        Cyk               = TIR.RCY1;
        Eyk               = min(TIR.REY1+TIR.REY2.*FzNom,1);
        num_gyk           = cos(Cyk.*atan(Byk.*k_s-Eyk.*(Byk.*k_s-atan(Byk.*k_s))));
        den_gyk           = cos(Cyk.*atan(Byk.*Shyk-Eyk.*(Byk.*Shyk-atan(Byk.*Shyk))));
        Gyk               = min(num_gyk./max(den_gyk,1e-6),1);
        Gyk(Gyk<0)        = 0;
        dVyk              = Muy.*Fz.*(TIR.RVY1+TIR.RVY2.*FzNom+TIR.RVY3.*opts.camber).*cos(atan(TIR.RVY4.*alpha));
        Svyk              = dVyk.*sin(TIR.RVY5.*atan(TIR.RVY6.*kappa));
        Fy                = Fy0.*Gyk+Svyk;
    end

    % helper — retrieve optional TIR coefficients
    function val = GetParam(name)
        if (isfield(TIR,name))&&(~isnan(TIR.(name))), val = TIR.(name);
        else,                                         val = 0;
        end
    end
end
